-- 核心职责：为 trace_spans 的墙上时钟开始时间建立索引，让保留期清理按截止时间分批定位过期跨度。
-- 交互契约：只新增索引，不改表结构与既有行；清理语句按 started_at 早于截止时间取一批行删除。
-- 约束与禁忌：started_at 为 NULL 的早期跨度不满足范围条件，不会被清理选中；索引不得改变跨度的写入与查询语义。

-- 没有该索引时，每一批删除都要从表头顺序扫描到凑满一批为止：
-- 未过期的行与没有墙上时钟的早期行会在每一批里被重复扫过，一次清理的成本随表规模成倍增长。
CREATE INDEX trace_spans_started_at ON trace_spans (started_at);
